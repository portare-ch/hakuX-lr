/* Ring-0 #BP handler at 0x7000 with IF clear. The site table at 0xC000
 * starts with a count, followed by sorted {eip, u16 routine, u8 length,
 * u8 family} entries for armed register forms; family 0 is RSQRT, 1 RCP.
 * A family's {lane routine, mantissa table} is at 0x7200 + 8 * family and
 * its 64-bit count of corrections at 0x7210 + 8 * family. Forward other
 * INT3 and INT 3 traps to the vector 3 stub at 0x4030 with the original
 * stack.
 *
 *  push eax
 *  push ecx
 *  push edx
 *  push ebx
 *  mov eax, [esp + 16]      # the EIP after the INT3
 *  lea eax, [eax - 1]       # the site
 *  xor ecx, ecx             # the search's low end
 *  mov edx, [SITES]         # and its high end: the count
 * next:
 *  cmp ecx, edx
 *  jae miss
 *  lea ebx, [ecx + edx]
 *  shr ebx, 1
 *  cmp eax, [ebx*8 + SITES + 4]
 *  je hit
 *  jb below
 *  lea ecx, [ebx + 1]
 *  jmp next
 * below:
 *  mov edx, ebx
 *  jmp next
 * miss:
 *  pop ebx
 *  pop edx
 *  pop ecx
 *  pop eax
 *  jmp STUB3
 * hit:
 *  movzx ecx, byte ptr [ebx*8 + SITES + 10]
 *  add eax, ecx             # past the instruction
 *  mov [esp + 16], eax
 *  movzx ecx, byte ptr [ebx*8 + SITES + 11]
 *  add dword ptr [ecx*8 + HITS], 1  # counted, for the log
 *  adc dword ptr [ecx*8 + HITS + 4], 0
 *  movzx eax, word ptr [ebx*8 + SITES + 8]
 *  mov edx, [ecx*8 + FAM + 4]
 *  mov ebx, [ecx*8 + FAM]
 *  call eax                 # the form's routine: EAX, ECX free, EBX the lane, EDX its table
 *  pop ebx
 *  pop edx
 *  pop ecx
 *  pop eax
 *  iret
 */
