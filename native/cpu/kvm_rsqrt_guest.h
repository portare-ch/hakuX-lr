/* Ring-0 #BP handler at 0x7000 with IF clear. The site table at 0xC000
 * starts with a count, followed by sorted {eip, u16 routine, u16 length}
 * entries for armed register forms. Forward other INT3 and INT 3 traps to
 * the vector 3 stub at 0x4030 with the original stack. Count corrections
 * in the 64-bit word at 0xFFF8.
 *
 *  push eax
 *  push ecx
 *  push edx
 *  push ebx
 *  mov eax, [esp + 16]      # the EIP after the INT3
 *  lea eax, [eax - 1]       # the site
 *  xor ecx, ecx             # the search's low end
 *  mov edx, [SITES]         # and its high end: the count
 * next:
 *  cmp ecx, edx
 *  jae miss
 *  lea ebx, [ecx + edx]
 *  shr ebx, 1
 *  cmp eax, [ebx*8 + SITES + 4]
 *  je hit
 *  jb below
 *  lea ecx, [ebx + 1]
 *  jmp next
 * below:
 *  mov edx, ebx
 *  jmp next
 * miss:
 *  pop ebx
 *  pop edx
 *  pop ecx
 *  pop eax
 *  jmp STUB3
 * hit:
 *  movzx ecx, word ptr [ebx*8 + SITES + 10]
 *  add eax, ecx             # past the instruction
 *  mov [esp + 16], eax
 *  add dword ptr [HITS], 1  # counted, for the log
 *  adc dword ptr [HITS + 4], 0
 *  movzx ecx, word ptr [ebx*8 + SITES + 8]
 *  pop ebx
 *  call ecx                 # the form's routine: EAX, ECX, EDX free
 *  pop edx
 *  pop ecx
 *  pop eax
 *  iret
 */
