/* The Intel result of one lane: EAX the input bits, EDX the 2048-entry
 * mantissa table (nc_rsqrt_intel's); EAX the result, ECX clobbered. The
 * same bytes mean the same in 32-bit and 64-bit mode (no inc/dec, no
 * push/pop), so a host test runs them natively against nc_rsqrt_intel.
 *
 *  mov ecx, eax
 *  and ecx, 0x7FFFFFFF
 *  cmp ecx, 0x7F800000
 *  ja nan
 *  cmp ecx, 0x00800000
 *  jb zero
 *  test eax, eax
 *  js negative
 *  cmp ecx, 0x7F800000
 *  je pinf
 *  mov ecx, eax
 *  shr ecx, 13
 *  and ecx, 2047
 *  movzx ecx, word ptr [edx + ecx*2]
 *  shl ecx, 11
 *  shr eax, 23
 *  neg eax
 *  add eax, 380
 *  shr eax, 1
 *  shl eax, 23
 *  or eax, ecx
 *  ret
 * nan:
 *  or eax, 0x00400000
 *  ret
 * zero:
 *  and eax, 0x80000000
 *  or eax, 0x7F800000
 *  ret
 * negative:
 *  mov eax, 0xFFC00000
 *  ret
 * pinf:
 *  xor eax, eax
 *  ret
 */
